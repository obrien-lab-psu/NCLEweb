#!/bin/bash
# Quick setup script for ncleweb.org with Cloudflare

echo "================================"
echo "NCLEWEB.ORG Setup Guide"
echo "================================"

echo ""
echo "Your domain: ncleweb.org"
echo "Status: Purchased through Cloudflare Registrar ✓"
echo "Nameservers: Automatically configured ✓"
echo ""

echo "STEP 1: Add Site to Cloudflare"
echo "-------------------------------"
echo "1. Go to: https://dash.cloudflare.com"
echo "2. Click 'Add a Site'"
echo "3. Enter: ncleweb.org"
echo "4. Select: Free Plan"
echo "5. Click Continue"
echo ""
echo "Press Enter when you've added the site..."
read

echo ""
echo "STEP 2: Configure DNS Records"
echo "------------------------------"
echo "You need your server's public IP address."
echo "Finding your IP..."
echo ""

SERVER_IP=$(curl -s ifconfig.me)
if [ -z "$SERVER_IP" ]; then
    echo "Could not auto-detect IP. Run manually:"
    echo "  curl ifconfig.me"
    echo ""
    echo "Enter your server IP:"
    read SERVER_IP
else
    echo "Detected server IP: $SERVER_IP"
    echo "Is this correct? (y/n)"
    read CONFIRM
    if [ "$CONFIRM" != "y" ]; then
        echo "Enter your server IP:"
        read SERVER_IP
    fi
fi

echo ""
echo "In Cloudflare DNS settings, add these records:"
echo ""
echo "Record 1 (A Record):"
echo "  Type: A"
echo "  Name: @"
echo "  IPv4: $SERVER_IP"
echo "  Proxy: ON (orange cloud) ← IMPORTANT"
echo "  TTL: Auto"
echo ""
echo "Record 2 (CNAME Record):"
echo "  Type: CNAME"
echo "  Name: www"
echo "  Target: ncleweb.org"
echo "  Proxy: ON (orange cloud) ← IMPORTANT"
echo "  TTL: Auto"
echo ""
echo "Press Enter when DNS records are added..."
read

echo ""
echo "STEP 3: Configure SSL/TLS"
echo "-------------------------"
echo "In Cloudflare Dashboard:"
echo "1. Go to: SSL/TLS → Overview"
echo "2. Set mode to: Full (strict)"
echo "3. Go to: Edge Certificates"
echo "4. Enable: Always Use HTTPS"
echo "5. Enable: Automatic HTTPS Rewrites"
echo ""
echo "Press Enter when SSL is configured..."
read

echo ""
echo "STEP 4: Security Settings"
echo "-------------------------"
echo "In Cloudflare Dashboard:"
echo "1. Go to: Security → Settings"
echo "2. Security Level: Medium"
echo "3. Challenge Passage: 30 minutes"
echo "4. Browser Integrity Check: ON"
echo ""
echo "Optional - Add Firewall Rule:"
echo "Go to: Security → WAF → Create rule"
echo "Name: Rate limit API submissions"
echo "Field: URI Path | contains | /api/submit-job"
echo "Action: Challenge if more than 5 requests in 1 minute"
echo ""
echo "Press Enter when security is configured..."
read

echo ""
echo "STEP 5: Deploy to Server"
echo "-------------------------"
echo "Now we'll deploy the application to your production server."
echo ""
echo "Is your production server ready? (y/n)"
read SERVER_READY

if [ "$SERVER_READY" = "y" ]; then
    echo ""
    echo "Run this on your PRODUCTION server (not WSL):"
    echo ""
    echo "  cd /home/ianms/git_repos/NCLEweb"
    echo "  git pull"
    echo "  sudo ./deploy/deploy.sh"
    echo ""
    echo "This will:"
    echo "  - Install Nginx with your domain configured"
    echo "  - Set up SSL with Let's Encrypt"
    echo "  - Create systemd service"
    echo "  - Start the application"
    echo ""
else
    echo ""
    echo "Set up your production server first, then run:"
    echo "  cd /home/ianms/git_repos/NCLEweb"
    echo "  git pull"
    echo "  sudo ./deploy/deploy.sh"
    echo ""
fi

echo ""
echo "STEP 6: Test Your Site"
echo "----------------------"
echo "After deployment, test:"
echo ""
echo "1. DNS Propagation:"
echo "   nslookup ncleweb.org"
echo "   (Should show Cloudflare IPs)"
echo ""
echo "2. Visit your site:"
echo "   https://ncleweb.org"
echo "   (Should load with SSL)"
